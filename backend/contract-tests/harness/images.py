"""Tiny, dependency-free image helpers for upload scenarios."""

from __future__ import annotations

import struct
import zlib


def png(width: int, height: int, rgb: tuple[int, int, int] = (40, 120, 200)) -> bytes:
    """A solid-colour RGB PNG (deterministic bytes)."""

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    row = b"\x00" + bytes(rgb) * width
    raw = row * height
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def image_info(data: bytes) -> dict[str, object]:
    """Format and dimensions of a JPEG or PNG (enough to compare server-side resizing)."""
    if data[:8] == b"\x89PNG\r\n\x1a\n" and len(data) >= 24:
        w, h = struct.unpack(">II", data[16:24])
        return {"format": "png", "width": w, "height": h}
    if data[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(data):
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
                i += 2
                continue
            seg_len = struct.unpack(">H", data[i + 2:i + 4])[0]
            if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                h, w = struct.unpack(">HH", data[i + 5:i + 9])
                return {"format": "jpeg", "width": w, "height": h}
            i += 2 + seg_len
        return {"format": "jpeg", "width": None, "height": None}
    return {"format": "unknown", "bytes": len(data)}
